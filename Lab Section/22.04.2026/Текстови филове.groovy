Работа с вход-изход. Текстови филове. Четене от файл. Запис във файл. (в C)

Какво е поток? 
Поток е абстрактно понятие, което представлява последователност от данни, 
която може да бъде четена или записвана. Входният поток (input stream) се 
използва за четене на данни, докато изходният поток (output stream) се използва 
за записване на данни.

Има два типа потоци. Текстов и двоичен.
Текстовия поток съдържа ASCII знакове, докато двоичния поток - изполва вякакъв тип данни.

Работа с файлове в C:
1. Отваряне на файл: За да работите с файл, първо трябва да го отворите с помощта на функцията 
fopen(). Тази функция приема два аргумента - името на файла и режима на отваряне 
(например "r" за четене, "w" за писане, "a" за добавяне).
1️⃣ ["rb" - за четене в двоичен режим, "wb" - за писане в двоичен режим, "ab" - за добавяне в двоичен 
режим]
2️⃣ {"r+" - за четене и писане, "w+" - за писане и четене (създава нов файл или изтрива съществуващ), 
"a+" - за добавяне и четене (създава нов файл или отваряне съществуващ)}
3️⃣ ("r+b"/"rb+" - за четене и писане в двоичен режим, "w+b"/"wb+" - за писане и четене в двоичен режим (създава нов файл или изтрива 
съществуващ), "a+b"/"ab+" - за добавяне и четене в двоичен режим (създава нов файл или отваря съществуващ))


2. Четене от файл: За да четете от файл, можете да използвате функции като 
fscanf(), fgetc() или fread(). Тези функции ви позволяват да четете данни от файла и да ги 
съхранявате в променливи или масиви.


3. Запис във файл: За да записвате във файл, можете да използвате функции като fprintf(), 
fputc() или fwrite(). Тези функции ви позволяват да записвате данни от променливи или масиви 
във файла.


4. Затваряне на файл: След като приключите с работата с файла,трябва да го затворите с помощта 
на функцията fclose(). Това освобождава ресурсите, свързани с файла, и гарантира, че всички данни 
са записани правилно.


Примерен код за четене от файл:
#include <stdio.h>
int main() 
{
    FILE *file = fopen("example.txt", "r");
    if (file == NULL) 
    {
        printf("Не може да се отвори файла.\n");
        return 1;
    } //Проверка дали файлът е отворен успешно
    
    char buffer[100];
    while (fgets(buffer, sizeof(buffer), file) != NULL) 
    {
        printf("%s", buffer);
    }
    
    int fgetc(FILE *file);

    int fputc(int character, FILE *file);

    int fclose(FILE *file);

    fclose(file); //Затваряне на файла
    return 0;
}

Пример за четене/запис на байтове (знаци) в C:
#include <stdio.h>
#include <stdlib.h>
int main()
{
    char str[80] = "This is a file system test.";
    FILE *fp;
    char *p;
    int i;

    if ((fp = fopen("myfile.txt", "w")) = NULL)
    {
        printf("Cannot open file.\n");
        return 1;
    }

    p = str;
    while (*p)
    {
        if (fputc(*p, fp) == EOF)
        {
            printf("Error writing to file.\n");
            return 1;
        }
        p++;
    }

    fclose(fp);

    if ((fp = fopen("myfile.txt", "r")) == NULL) //отваряне на файла за четене/писане
    {
        printf("Cannot open file.\n");
        return 1;
    }

    for(;;) //четене от файла до края му
    {
        i = getc(fp);
        if (i == EOF)
        {
            break;
        }
        putchar(i);
    }
    fclose(fp);
    return 0;
}   

