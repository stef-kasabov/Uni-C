Четене и запис на двоични данни в C:
Образен запис/шаблон за четене и запис на двоични данни в C:
size_t fread(void *ptr, size_t size, size_t count, FILE *stream);
size_t fwrite(void *ptr, size_t size, size_t count, FILE *stream);

Примерен код за четене и запис на двоични данни в C:
#include <stdio.h>
#include <stdlib.h>
int main ()
{
    FILE *fp;
    int i;

    if ((fp = fopen("binaryfile.bin", "wb")) == NULL)
    {
        printf("Cannot open file.\n");
        return 1;
    }

    i = 100;

    if(fwrite(&i, sizeof(int), 1, fp) != 1)
    {
        printf("Error writing to file.\n");
        return 1;
    }
    fclose(fp);

    if ((fp = fopen("binaryfile.bin", "rb")) == NULL)
    {
        printf("Cannot open file.\n");
        return 1;
    }

    if(fread(&i, sizeof(int), 1, fp) != 1)
    {
        printf("Error reading from file.\n");
        return 1;
    }
    printf("Read from file [i]: %d\n", i);
    
    fclose(fp);
    return 0;
}


Прозиволен достъп до файл в C:
Прозиволният достъп до файл позволява да се четат или записват данни на произволна позиция във файла, без да е необходимо да се 
чете или записва последователно от началото. Това може да бъде полезно за работа с големи файлове или за обновяване на определени 
части от файла.
За да се осъществи произволен достъп до файл в C, се използват функциите fseek() и ftell(). Функцията fseek() се използва за
придвижване на позицията на файла до определено място, докато функцията ftell() се използва за получаване на текущата позиция на файла.

Записна на fseek():
int fseek(FILE *filename, long offset, int start);

Стойността на отместване може да бъде положителна или отрицателна, в зависимост от това дали искате да се придвижите напред 
или назад от началната позиция.

SEEK_SET: Позицията се задава спрямо началото на файла. Отместването се изчислява от началото на файла.
SEEK_CUR: Позицията се задава спрямо текущата позиция на файла
SEEK_END: Позицията се задава спрямо края на файла. Отместването се изчислява от края на файла.

Записване на ftell():
long ftell(FILE *filename);
Функцията ftell() връща текущата позиция на файла като брой байтове от началото на файла. Това може да бъде полезно за 
запазване на текущата позиция, преди да се извърши произволен достъп, и за възстановяване на тази позиция по-късно.


Позициониране, Преименуване и изтриване на файлове в C:
За позициониране на файл в C, се използва функцията fseek(), която позволява да се придвижите до определена позиция във файла.


За преименуване на файл в C, се използва функцията rename(), която приема два аргумента - старото име на файла и новото име на файла. 
Ако преименуването е успешно, функцията връща 0, в противен случай връща ненулева стойност.
int rename(char *old_filename, const char *new_filename);

За изтриване на файл в C, се използва функцията remove(), която приема един аргумент - името на файла, който да бъде изтрит. 
Ако изтриването е успешно, функцията връща 0, в противен случай връща ненулева стойност.
int remove(char *filename);

