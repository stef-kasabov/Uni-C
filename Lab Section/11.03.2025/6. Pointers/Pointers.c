#include <stdio.h>

/*
6.	Напишете програма, която демонстрира указатели (декларация, присвояване на адрес на променлива, извеждане на адреса + стойността на променливата на екрана).
*/

int main() 
{
    int num = 42; 
    int *ptr = &num; 
    
    printf("Address of num: %p\n", (void*)ptr); // Адресът на променливата
    printf("Value of num: %d\n", *ptr); // Стойността на променливата чрез указателя
    
    return 0;
}